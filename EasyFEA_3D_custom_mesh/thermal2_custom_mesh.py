"""Thermal2 with an arbitrary 3D custom mesh.

This is ``examples/Thermal/Thermal2.py`` with the mesh block replaced by the
custom mesh input interface.  The physics is unchanged:

- square prism with a circular hole along z (default demo);
- left face T=0, right face T=40, other faces adiabatic;
- transient heat conduction, theta=0.5, dt=Tmax/steps;
- initial temperature 0.

Examples
--------
Exact Thermal2 geometry, generated by gmsh then solved through the custom
interface and compared with the original mesh::

    python thermal2_custom_mesh.py --demo thermal2 --elem-type TETRA4

Pure hand-built 3D mesh (square prism with a square through-hole), no gmsh::

    python thermal2_custom_mesh.py --demo box --n 6 --nz 2 --scale 1

Your own 3D mesh file::

    python thermal2_custom_mesh.py --mesh mesh.json --bc left:0 --bc right:40
"""

from __future__ import annotations

import env_compat  # noqa: F401  (must precede NumPy/EasyFEA)

import argparse
import sys
from pathlib import Path

import numpy as np

from EasyFEA import Models, Simulations

import custom_mesh as cm
from demo_meshes import mesh_to_data
from demo_meshes_3d import hollow_box_mesh, thermal2_mesh
from thermal_custom_mesh import parse_bcs, resolve_bc_nodes, solve_thermal


# ---------------------------------------------------------------------------
# solver
# ---------------------------------------------------------------------------


def solve_transient(
    mesh,
    bcs_nodes,
    *,
    tmax: float = 0.5,
    steps: int = 20,
    alpha: float = 0.5,
    k: float = 1.0,
    c: float = 1.0,
    rho: float = 1.0,
):
    """Same time integration as Thermal2 (theta scheme, dt = tmax / steps)."""

    if tmax <= 0:
        raise ValueError("tmax must be positive.")
    if steps < 1:
        raise ValueError("steps must be >= 1.")

    dt = tmax / steps
    model = Models.Thermal(k=k, c=c)
    simu = Simulations.Thermal(mesh, model)
    simu.rho = rho

    for nodes, value in bcs_nodes:
        if nodes.size == 0:
            raise RuntimeError("A boundary condition selected zero nodes.")
        simu.add_dirichlet(nodes, [value], ["t"])

    simu.Solver_Set_Parabolic_Algorithm(alpha=alpha, dt=dt)

    for _ in range(steps):
        simu.Solve()
        simu.Save_Iter()

    return simu, np.asarray(simu.thermal).ravel()


def boundary_nodes(mesh) -> np.ndarray:
    """Boundary nodes from a tag or from the lower-dimensional groups."""

    tags = cm.available_tags(mesh)
    if "boundary" in tags:
        return np.asarray(mesh.Nodes_Tags("boundary"), dtype=np.int64)

    nodes: set[int] = set()
    for group_elem in mesh.dict_groupElem.values():
        if group_elem.dim < mesh.dim:
            nodes.update(np.asarray(group_elem.nodes, int).tolist())
    return np.asarray(sorted(nodes), dtype=np.int64)


def patch_test(mesh) -> float | None:
    """Prescribe T=2x+3y+4z on all boundary nodes; return max nodal error."""

    nodes = boundary_nodes(mesh)
    if nodes.size == 0:
        return None

    simu = solve_thermal(
        mesh, [(nodes, lambda x, y, z: 2.0 * x + 3.0 * y + 4.0 * z)]
    )
    temperature = np.asarray(simu.thermal).ravel()
    coords = np.asarray(mesh.coord)
    exact = 2.0 * coords[:, 0] + 3.0 * coords[:, 1] + 4.0 * coords[:, 2]
    return float(np.max(np.abs(temperature - exact)))


# ---------------------------------------------------------------------------
# output
# ---------------------------------------------------------------------------


def save_results(path: str | Path, mesh, temperature: np.ndarray) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    coords = np.asarray(mesh.coord)
    table = np.column_stack(
        [
            np.arange(mesh.Nn),
            coords[:, 0],
            coords[:, 1],
            coords[:, 2],
            temperature,
        ]
    )
    np.savetxt(
        path,
        table,
        delimiter=",",
        header="node,x,y,z,t",
        comments="",
        fmt=["%d", "%.17g", "%.17g", "%.17g", "%.17g"],
    )
    return path


# ---------------------------------------------------------------------------
# command line
# ---------------------------------------------------------------------------


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Thermal2 transient simulation on a custom 3D mesh."
    )
    parser.add_argument("--demo", choices=("thermal2", "box"), default="thermal2")
    parser.add_argument("--elem-type", default=None,
                        help="3D element type (default: TETRA4 for thermal2, HEXA8 for box)")
    parser.add_argument("--a", type=float, default=1.0, help="Thermal2 geometry size")
    parser.add_argument("--n", type=int, default=6, help="box: cells per unit length")
    parser.add_argument("--nz", type=int, default=2, help="box: layers through thickness")
    parser.add_argument("--scale", type=float, default=1.0, help="box: geometry scale")
    parser.add_argument("--mesh", default=None,
                        help="3D mesh file: .json/.npz/.msh or CSV directory")
    parser.add_argument("--nodes", default=None, help="CSV/TXT 3D nodal coordinates")
    parser.add_argument("--elements", default=None, help="CSV/TXT element connectivity")
    parser.add_argument("--index-base", type=int, choices=(0, 1), default=None)
    parser.add_argument("--tags", default=None, help="JSON file of node tags")
    parser.add_argument("--bc", action="append", default=None, metavar="SPEC:VALUE",
                        help="Dirichlet BC, e.g. left:0 or xmin:0 (repeatable)")
    parser.add_argument("--tmax", type=float, default=0.5)
    parser.add_argument("--steps", type=int, default=20)
    parser.add_argument("--alpha", type=float, default=0.5)
    parser.add_argument("--k", type=float, default=1.0)
    parser.add_argument("--c", type=float, default=1.0)
    parser.add_argument("--rho", type=float, default=1.0)
    parser.add_argument("--tol", type=float, default=None)
    parser.add_argument("--no-patch-test", action="store_true")
    parser.add_argument("--no-compare", action="store_true",
                        help="do not run the built-in Thermal2 reference")
    parser.add_argument("--export", default=None,
                        help="write the demo mesh to .json/.npz (or directory)")
    parser.add_argument("--save", nargs="?", const="auto", default=None,
                        help="save final nodal temperature to CSV")
    return parser


def _run(args) -> int:
    if args.mesh and (args.nodes or args.elements):
        raise ValueError("Use either --mesh or --nodes/--elements, not both.")
    if bool(args.nodes) != bool(args.elements):
        raise ValueError("--nodes and --elements must be provided together.")

    builtin_mesh = None
    data = None
    expected_volume = None
    name = "custom3d"

    if args.mesh:
        mesh = cm.load_mesh(
            args.mesh,
            elem_type=args.elem_type,
            index_base=args.index_base,
            verbose=True,
        )
        name = Path(args.mesh).stem
    elif args.nodes:
        if args.elem_type is None:
            raise ValueError("--elem-type is required with --nodes/--elements.")
        data = cm.load_nodes_elements(
            args.nodes,
            args.elements,
            elem_type=args.elem_type,
            index_base=0 if args.index_base is None else args.index_base,
            node_tags=args.tags,
        )
        mesh = cm.build_mesh(data, verbose=True)
        name = Path(args.nodes).stem
    else:
        if args.demo == "thermal2":
            elem_type = args.elem_type or "TETRA4"
            data, builtin_mesh = thermal2_mesh(elem_type, a=args.a)
            mesh = cm.build_mesh(data, verbose=True)
            name = f"thermal2_{elem_type}"
        else:
            if args.elem_type is not None and str(cm.as_elem_type(args.elem_type)) != "HEXA8":
                raise ValueError("The box demo only generates HEXA8.")
            data = hollow_box_mesh(n=args.n, nz=args.nz, scale=args.scale)
            mesh = cm.build_mesh(data, verbose=True)
            expected_volume = 8.0 * args.scale**3
            name = "hollow_box_HEXA8"

    if mesh.dim != 3:
        raise ValueError(f"Expected a 3D mesh, got {mesh.dim}D.")

    if args.export:
        export_data = data if data is not None else mesh_to_data(mesh)
        cm.save_mesh_data(export_data, args.export)
        print(f"[export] {args.export}")

    info = cm.mesh_info(mesh)
    quality = info["quality_min"]
    quality_text = f"{quality:.4g}" if quality is not None else "n/a"
    print(
        f"\nMesh     : {info['elem_type']}, Nn={info['Nn']}, Ne={info['Ne']}, "
        f"volume={info['volume']:.10g}, min quality={quality_text}"
    )
    print(f"Tags     : {info['tags'] or 'none'}")

    failures: list[str] = []

    if expected_volume is not None:
        volume_error = abs(info["volume"] - expected_volume)
        print(
            f"Volume   : {info['volume']:.12g} "
            f"(exact {expected_volume:g}, error {volume_error:.2e})"
        )
        if volume_error > 1e-10 * max(1.0, expected_volume):
            failures.append("volume mismatch")

    if not args.no_patch_test:
        patch_error = patch_test(mesh)
        if patch_error is None:
            print("Patch    : skipped (no boundary tag / boundary groups)")
        else:
            print(f"Patch    : max |T-(2x+3y+4z)| = {patch_error:.3e}")
            if patch_error > 1e-8:
                failures.append("3D patch test")

    bcs = parse_bcs(args.bc)
    bcs_nodes = []
    for spec, value in bcs:
        nodes = resolve_bc_nodes(mesh, spec, tol=args.tol)
        if nodes.size == 0:
            raise RuntimeError(f"Boundary condition {spec!r} selected no nodes.")
        bcs_nodes.append((nodes, value))
        print(f"BC       : {spec} -> {nodes.size} nodes, T={value:g}")

    simu, temperature = solve_transient(
        mesh,
        bcs_nodes,
        tmax=args.tmax,
        steps=args.steps,
        alpha=args.alpha,
        k=args.k,
        c=args.c,
        rho=args.rho,
    )
    print(
        f"Transient: {args.steps} steps, dt={args.tmax / args.steps:g}, "
        f"theta={args.alpha:g}"
    )
    print(
        f"Results  : Tmin={temperature.min():.8g}, "
        f"Tmax={temperature.max():.8g}, mean={temperature.mean():.8g}, "
        f"nodes={temperature.size}"
    )
    if float(temperature.min()) < -1e-10 or float(temperature.max()) > 40.0 + 1e-10:
        failures.append("temperature outside [0,40]")

    if builtin_mesh is not None and not args.no_compare:
        volume_difference = abs(
            float(info["volume"]) - float(builtin_mesh.volume)
        )
        print(
            f"Volume   : custom={info['volume']:.12g}, "
            f"Thermal2={builtin_mesh.volume:.12g}, "
            f"error={volume_difference:.1e}"
        )
        if volume_difference > 1e-12:
            failures.append("volume comparison")

        reference_simu, reference_temperature = solve_transient(
            builtin_mesh,
            bcs_nodes,
            tmax=args.tmax,
            steps=args.steps,
            alpha=args.alpha,
            k=args.k,
            c=args.c,
            rho=args.rho,
        )
        if reference_temperature.size != temperature.size:
            raise RuntimeError("Built-in and custom meshes have different node counts.")
        difference = float(np.max(np.abs(temperature - reference_temperature)))
        print(f"Compare  : max |T_custom - T_Thermal2| = {difference:.3e}")
        if difference > 1e-8:
            failures.append("Thermal2 comparison")

    if args.save:
        path = (
            Path("results") / f"{name}_transient.csv"
            if args.save == "auto"
            else Path(args.save)
        )
        saved = save_results(path, mesh, temperature)
        print(f"Saved    : {saved}")

    if failures:
        print("\nFAILED checks: " + ", ".join(failures))
        return 1
    print("\n3D thermal simulation completed and all checks passed.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    try:
        return _run(args)
    except (ValueError, cm.MeshInputError, RuntimeError) as exc:
        parser.exit(2, f"error: {exc}\n")


if __name__ == "__main__":
    sys.exit(main())
