"""Self-describing datasets: generation, loading, discovery and splitting.

A dataset is a CSV file with one simulation per row,
``[input_1, ..., input_k, output_1, ..., output_m]``, accompanied by a JSON
*sidecar* (same name, ``.json`` extension) holding a :class:`DatasetSpec`:
which inputs it has and how many outputs. Models use the spec to check that
they are compatible with a dataset before any training starts.
"""

from __future__ import annotations

import datetime
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np

from . import config

DEFAULT_DATA_DIR = Path("data")


# --------------------------------------------------------------------------
# Specification
# --------------------------------------------------------------------------
@dataclass
class DatasetSpec:
    """Shape and meaning of a dataset.

    Attributes
    ----------
    name : str
        Human-readable name.
    input_names : list[str]
        Names of the input columns, in order (e.g. ``["T0", "P0", "h"]``).
    n_outputs : int
        Number of output values per sample.
    output_kind : str
        What the outputs are (e.g. ``"nodal_temperature"``).
    mesh_id : str or None
        Identifier of the mesh the outputs live on; two datasets only share
        output semantics if they share this id.
    input_ranges : dict
        Sampling range ``(min, max)`` per input, used when generating data.
    """

    name: str
    input_names: list[str]
    n_outputs: int
    output_kind: str = "nodal_temperature"
    mesh_id: str | None = None
    input_ranges: dict[str, tuple[float, float]] = field(default_factory=dict)

    @property
    def n_inputs(self) -> int:
        return len(self.input_names)

    @property
    def n_columns(self) -> int:
        return self.n_inputs + self.n_outputs

    def describe(self) -> str:
        return (
            f"{self.n_inputs} inputs ({', '.join(self.input_names)}) -> "
            f"{self.n_outputs} outputs ({self.output_kind}, mesh={self.mesh_id})"
        )

    def to_dict(self) -> dict:
        d = asdict(self)
        d["input_ranges"] = {k: list(v) for k, v in self.input_ranges.items()}
        return d

    @classmethod
    def from_dict(cls, d: dict) -> "DatasetSpec":
        d = dict(d)
        d["input_ranges"] = {k: tuple(v) for k, v in d.get("input_ranges", {}).items()}
        return cls(**d)


def make_spec(input_names=("T0", "P0", "h"), name: str = "cube") -> DatasetSpec:
    """Spec of a dataset generated by :mod:`simulation` varying ``input_names``."""
    input_names = list(input_names)
    unknown = [n for n in input_names if n not in config.PARAM_RANGES]
    if unknown:
        raise ValueError(
            f"Unknown input parameter(s) {unknown}; available: {sorted(config.PARAM_RANGES)}"
        )
    if len(set(input_names)) != len(input_names):
        raise ValueError("Duplicate input parameters.")
    return DatasetSpec(
        name=name,
        input_names=input_names,
        n_outputs=config.N_NODES,
        output_kind="nodal_temperature",
        mesh_id=config.MESH_ID,
        input_ranges={n: config.PARAM_RANGES[n] for n in input_names},
    )


# CSVs created before sidecars existed: 563 columns = (T0, P0, h) + 560 nodes.
LEGACY_SPEC = make_spec(("T0", "P0", "h"), name="legacy")


def spec_path(csv_path: str | Path) -> Path:
    return Path(csv_path).with_suffix(".json")


def save_spec(spec: DatasetSpec, csv_path: str | Path) -> Path:
    path = spec_path(csv_path)
    path.write_text(json.dumps(spec.to_dict(), indent=2), encoding="utf-8")
    return path


def _count_columns(csv_path: Path) -> int:
    with csv_path.open() as f:
        return len(f.readline().strip().split(","))


def load_spec(csv_path: str | Path) -> DatasetSpec:
    """Read the sidecar of ``csv_path``.

    Falls back to :data:`LEGACY_SPEC` for sidecar-less CSVs with the legacy
    number of columns; any other sidecar-less CSV is rejected.
    """
    csv_path = Path(csv_path)
    sidecar = spec_path(csv_path)
    if sidecar.exists():
        return DatasetSpec.from_dict(json.loads(sidecar.read_text(encoding="utf-8")))

    n_cols = _count_columns(csv_path)
    if n_cols == LEGACY_SPEC.n_columns:
        return LEGACY_SPEC
    raise ValueError(
        f"{csv_path.name} has {n_cols} columns and no description file "
        f"'{sidecar.name}'. Create it (see DatasetSpec) so models can check "
        "compatibility."
    )


# --------------------------------------------------------------------------
# Discovery
# --------------------------------------------------------------------------
def resolve_dataset(name_or_path: str | Path, data_dir: str | Path = DEFAULT_DATA_DIR) -> Path:
    """Return the CSV path for a file path or a bare dataset name in ``data_dir``."""
    candidate = Path(name_or_path)
    if candidate.is_file():
        return candidate
    data_dir = Path(data_dir)
    for option in (data_dir / candidate, data_dir / f"{candidate}.csv"):
        if option.is_file():
            return option
    available = [p.stem for p in sorted(data_dir.glob("*.csv"))] if data_dir.is_dir() else []
    raise FileNotFoundError(
        f"Dataset '{name_or_path}' not found (looked in '{data_dir}'). "
        f"Available: {available or 'none'}"
    )


def list_datasets(data_dir: str | Path = DEFAULT_DATA_DIR):
    """List ``(csv_path, spec_or_None, error_or_None)`` for every CSV in ``data_dir``."""
    out = []
    for path in sorted(Path(data_dir).glob("*.csv")):
        try:
            out.append((path, load_spec(path), None))
        except ValueError as exc:
            out.append((path, None, str(exc)))
    return out


# --------------------------------------------------------------------------
# Generation
# --------------------------------------------------------------------------
def create_dataset(
    n: int,
    spec: DatasetSpec | None = None,
    seed: int | None = None,
    verbose: bool = True,
) -> np.ndarray:
    """Run ``n`` simulations with inputs drawn uniformly in ``spec.input_ranges``.

    Returns
    -------
    numpy.ndarray
        Array of shape ``(n, spec.n_columns)``.
    """
    from .simulation import run_simulation

    spec = spec or LEGACY_SPEC
    rng = np.random.default_rng(seed)
    data = np.zeros((n, spec.n_columns))
    for i in range(n):
        inputs = {k: rng.uniform(*spec.input_ranges[k]) for k in spec.input_names}
        field_ = run_simulation(**inputs)
        data[i] = np.concatenate(([inputs[k] for k in spec.input_names], field_))
        if verbose:
            print(f"Simulation {i + 1}/{n} done")
    return data


def save_dataset(
    n: int,
    folder: str | Path = DEFAULT_DATA_DIR,
    seed: int | None = None,
    input_names=("T0", "P0", "h"),
) -> Path:
    """Generate ``n`` simulations; write a timestamped CSV and its JSON sidecar."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)

    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    stem = f"dataset_{stamp}_{n}"
    spec = make_spec(input_names, name=stem)

    data = create_dataset(n, spec, seed=seed)
    path = folder / f"{stem}.csv"
    np.savetxt(path, data, delimiter=",")
    save_spec(spec, path)

    print(f"Dataset saved in: {path} ({spec.describe()})")
    return path


# --------------------------------------------------------------------------
# Loading and splitting
# --------------------------------------------------------------------------
@dataclass
class Dataset:
    """Inputs ``X`` (n, n_inputs), outputs ``Y`` (n, n_outputs) and their spec."""

    X: np.ndarray
    Y: np.ndarray
    spec: DatasetSpec

    def __len__(self) -> int:
        return len(self.X)


def load_dataset(path: str | Path) -> Dataset:
    """Load and validate a dataset CSV against its spec (float32 arrays)."""
    path = Path(path)
    spec = load_spec(path)
    data = np.loadtxt(path, delimiter=",", ndmin=2)

    if data.shape[1] != spec.n_columns:
        raise ValueError(
            f"{path.name}: expected {spec.n_columns} columns "
            f"({spec.n_inputs} inputs + {spec.n_outputs} outputs), got {data.shape[1]}"
        )
    if len(data) < 3:
        raise ValueError("At least 3 samples are required.")
    if not np.isfinite(data).all():
        raise ValueError("Dataset contains NaN or infinite values.")

    return Dataset(
        X=data[:, : spec.n_inputs].astype(np.float32),
        Y=data[:, spec.n_inputs :].astype(np.float32),
        spec=spec,
    )


@dataclass
class Split:
    """Indices of the train / validation / test subsets."""

    train: np.ndarray
    val: np.ndarray
    test: np.ndarray


def split_indices(n: int, seed: int, test_frac: float = 0.15, val_frac: float = 0.15) -> Split:
    """Randomly split ``range(n)`` (at least one sample in test and val)."""
    perm = np.random.default_rng(seed).permutation(n)
    n_test = max(1, round(n * test_frac))
    n_val = max(1, round(n * val_frac))
    return Split(
        test=perm[:n_test],
        val=perm[n_test : n_test + n_val],
        train=perm[n_test + n_val :],
    )
